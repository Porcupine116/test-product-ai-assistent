def build_user_prompt(product: ProductInput) -> str:

    product_data = product.model_dump(
        mode="json",
        exclude_none=True
    )

    return (
        "Подготовь черновик товарной карточки "
        "на основании следующих данных:\n\n"
        f"{json.dumps(product_data, ensure_ascii=False, indent=2)}\n\n"
        "Следуй всем правилам системной инструкции. "
        "Верни только JSON заданной структуры."
    )